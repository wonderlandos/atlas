"""tokens.py: the WolOS tokens for the engine's WebUI pages (settings, history, downloads, ...).

The design repo's tokens/colors.json is the one source (python3 -I design/tools/tokens.py writes it
and its CSS). This script reads it and writes the CSS variable block that patch 0072 puts at the top
of ui/webui/resources/cr_elements/cr_shared_vars.css. The block is never edited by hand.

  python3 -I atlas/transform/tokens.py --css DESIGN_REPO          print the block
  python3 -I atlas/transform/tokens.py --check DESIGN_REPO        fail on drift:
        1. the block inside atlas/patches/ui/0072-webui-tokens.patch equals the generated one
        2. the radii in the design repo equal the numbers of the native chrome
           (chrome/browser/ui/atlas/chrome/atlas_tokens.h, which patch 0070 and its unit test hold
           equal to layout_constants.cc and layout_provider.cc)
  python3 -I atlas/transform/tokens.py --write DESIGN_REPO        rewrite the block in the patch
                                                                  and fix its hunk header

The design repo to pass is the OS one on the integration line (wave3/int): it is the source of
truth for the radii (8/12/16/12) and the accent; tokens.md section 1 is older.

Colours of the WebUI pages come from the browser's colour provider (chrome://theme/colors.css,
which the native mixer fills from the system theme), so the block carries only what that does not:
the accent as the fallback of --helium-blue (before colors.css is loaded), the radii, the type.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
PATCH = os.path.join(ROOT, "atlas", "patches", "ui", "0072-webui-tokens.patch")
TOKENS_H = os.path.join(ROOT, "chrome", "browser", "ui", "atlas", "chrome", "atlas_tokens.h")
BEGIN = "/* atlas-tokens:begin generated by atlas/transform/tokens.py; do not edit */"
END = "/* atlas-tokens:end */"

# design radius key -> constant of atlas_tokens.h
RADII = {"sm": "kRadiusControl", "md": "kRadiusCard", "lg": "kRadiusLarge", "window": "kRadiusWindow"}


def load(design):
    path = os.path.join(design, "tokens", "colors.json")
    try:
        with open(path, encoding="utf-8") as f:
            d = json.load(f)
    except (OSError, ValueError) as e:
        raise SystemExit("tokens.py: cannot read %s: %s" % (path, e))
    for key in ("accent", "radius", "font"):
        if key not in d:
            raise SystemExit("tokens.py: %s has no '%s'" % (path, key))
    return d


def px(value):
    m = re.fullmatch(r"(\d+)px", value)
    if not m:
        raise SystemExit("tokens.py: radius '%s' is not N px" % value)
    return int(m.group(1))


def block(d):
    """The CSS block as a list of lines (no trailing newline)."""
    fam = ", ".join(("'%s'" % x if " " in x else x) for x in d["font"]["ui-fallback"])
    size = d["font"]["size"]
    r = d["radius"]
    lines = [
        BEGIN,
        ":root {",
        "  --atlas-accent: %s;" % d["accent"]["light"],
        "  --atlas-radius-control: %dpx;" % px(r["sm"]),
        "  --atlas-radius-card: %dpx;" % px(r["md"]),
        "  --atlas-radius-large: %dpx;" % px(r["lg"]),
        "  --atlas-radius-window: %dpx;" % px(r["window"]),
        "  --atlas-font-ui: %s;" % fam,
        "  --atlas-font-size: %s;" % size,
        "}",
        "@media (prefers-color-scheme: dark) {",
        "  :root {",
        "    --atlas-accent: %s;" % d["accent"]["dark"],
        "  }",
        "}",
        END,
    ]
    return lines


def read_constants():
    out = {}
    with open(TOKENS_H, encoding="utf-8") as f:
        for m in re.finditer(r"inline constexpr int (k\w+) = (\d+);", f.read()):
            out[m.group(1)] = int(m.group(2))
    return out


def patch_block(text):
    """(start, end) line indexes of the block lines (with the leading '+') inside the patch text."""
    lines = text.split("\n")
    b = [i for i, ln in enumerate(lines) if ln == "+" + BEGIN]
    e = [i for i, ln in enumerate(lines) if ln == "+" + END]
    if len(b) != 1 or len(e) != 1 or e[0] < b[0]:
        raise SystemExit("tokens.py: the patch needs exactly one block between the begin and end markers")
    return lines, b[0], e[0]


def check(design):
    d = load(design)
    problems = []
    consts = read_constants()
    for key, const in RADII.items():
        if const not in consts:
            problems.append("atlas_tokens.h has no %s" % const)
        elif consts[const] != px(d["radius"][key]):
            problems.append("radius %s: design repo %s, atlas_tokens.h %s=%d" % (key, d["radius"][key], const, consts[const]))
    with open(PATCH, encoding="utf-8") as f:
        lines, b, e = patch_block(f.read())
    have = [ln[1:] for ln in lines[b:e + 1]]
    if have != block(d):
        problems.append("the block in %s differs from the one generated from %s (run --write)" % (os.path.relpath(PATCH, ROOT), design))
    for p in problems:
        print("tokens.py: " + p, file=sys.stderr)
    if not problems:
        print("tokens.py: ok (radii %s, block %d lines)" % (",".join(str(consts[c]) for c in RADII.values()), len(have)))
    return 1 if problems else 0


def write(design):
    d = load(design)
    with open(PATCH, encoding="utf-8") as f:
        lines, b, e = patch_block(f.read())
    new = ["+" + ln for ln in block(d)]
    lines[b:e + 1] = new
    # fix the hunk header of the hunk that holds the block: count its lines again
    h = max(i for i in range(b) if lines[i].startswith("@@ "))
    m = re.fullmatch(r"@@ -(\d+),(\d+) \+(\d+),(\d+) @@(.*)", lines[h])
    if not m:
        raise SystemExit("tokens.py: unexpected hunk header %r" % lines[h])
    j = h + 1
    old_n = new_n = 0
    while j < len(lines) and not lines[j].startswith(("@@ ", "--- ", "diff ")):
        ln = lines[j]
        if ln.startswith("+"):
            new_n += 1
        elif ln.startswith("-"):
            old_n += 1
        elif ln.startswith(" ") or ln == "":
            if ln == "" and j == len(lines) - 1:
                break
            old_n += 1
            new_n += 1
        j += 1
    lines[h] = "@@ -%s,%d +%s,%d @@%s" % (m.group(1), old_n, m.group(3), new_n, m.group(5))
    with open(PATCH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("tokens.py: wrote %d lines into %s" % (len(new), os.path.relpath(PATCH, ROOT)))
    return 0


def main(argv):
    if len(argv) != 3 or argv[1] not in ("--css", "--check", "--write"):
        print(__doc__, file=sys.stderr)
        return 2
    design = argv[2]
    if argv[1] == "--css":
        print("\n".join(block(load(design))))
        return 0
    return check(design) if argv[1] == "--check" else write(design)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
