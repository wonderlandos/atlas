"""Write theme.css (the preview tokens) from the two built-in WolOS themes.

The engine replaces theme.css with the live theme block (patches P-16/P-17,
see README.md); this file only exists so the page renders on its own.

usage: python3 -I tools/gen_theme.py <wolos-src> [--check]
  <wolos-src>  the WolOS tree (split/wolos): reads
               crates/core/src/theme/builtin/wol-{light,dark}.json and the
               SCALE table of crates/shared/src/theme.rs
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
OUT = HERE / "theme.css"


def kebab(token: str) -> str:
    return "--" + re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), token)


def tokens(src: pathlib.Path, name: str) -> dict:
    data = json.loads((src / "crates/core/src/theme/builtin" / f"{name}.json").read_text())
    return data["tokens"]


def scale(src: pathlib.Path) -> list:
    text = (src / "crates/shared/src/theme.rs").read_text()
    block = text.split("pub const SCALE", 1)[1].split("];", 1)[0]
    return re.findall(r'\("(--[a-z0-9-]+)",\s*"([^"]+)"\)', block)


def block(tok: dict, indent: str) -> str:
    return "".join(f"{indent}{kebab(k)}: {v};\n" for k, v in tok.items())


def render(src: pathlib.Path) -> str:
    light, dark = tokens(src, "wol-light"), tokens(src, "wol-dark")
    sc = "".join(f"  {k}: {v};\n" for k, v in scale(src))
    return (
        "/* Generated by tools/gen_theme.py from crates/core/src/theme/builtin/wol-light.json,\n"
        "   wol-dark.json and shared::theme::SCALE. Do not edit by hand.\n"
        "   Preview only: inside Atlas the engine serves the live WolOS theme under this\n"
        "   same name, so a theme change reaches the page with no code (README.md). */\n"
        ":root {\n  color-scheme: light;\n" + block(light, "  ") + sc + "}\n"
        "@media (prefers-color-scheme: dark) {\n  :root {\n    color-scheme: dark;\n"
        + block(dark, "    ") + "  }\n}\n"
    )


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    css = render(pathlib.Path(sys.argv[1]))
    if "--check" in sys.argv[2:]:
        if OUT.read_text() != css:
            print("theme.css is stale: run tools/gen_theme.py", file=sys.stderr)
            return 1
        print("theme.css matches the built-in themes")
        return 0
    OUT.write_text(css)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
