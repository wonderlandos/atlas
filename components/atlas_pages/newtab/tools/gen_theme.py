"""Write theme.css and categories.css (the preview tokens) from the WolOS tree and the design set.

The engine replaces both files with the live ones (theme.css: the 13 theme tokens and the scale
of the active WolOS theme; categories.css: the category colours of the design palette); these
copies only exist so the page renders on its own.

usage: python3 -I tools/gen_theme.py <wolos-src> [--check]
  <wolos-src>  the WolOS tree (split/wolos): reads
               crates/core/src/theme/builtin/wol-{light,dark}.json, the SCALE table of
               crates/shared/src/theme.rs and design/tokens/colors.json (icon.categories)
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
OUT_THEME = HERE / "theme.css"
OUT_CATS = HERE / "categories.css"
CATEGORIES = ("web", "talk", "files", "media", "store", "system")


def kebab(token: str) -> str:
    return "--" + re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), token)


def tokens(src: pathlib.Path, name: str) -> dict:
    data = json.loads((src / "crates/core/src/theme/builtin" / f"{name}.json").read_text())
    return data["tokens"]


def scale(src: pathlib.Path) -> list:
    text = (src / "crates/shared/src/theme.rs").read_text()
    block = text.split("pub const SCALE", 1)[1].split("];", 1)[0]
    return re.findall(r'\("(--[a-z0-9-]+)",\s*"([^"]+)"\)', block)


def block(tok: dict, indent: str) -> str:
    return "".join(f"{indent}{kebab(k)}: {v};\n" for k, v in tok.items())


def render_theme(src: pathlib.Path) -> str:
    light, dark = tokens(src, "wol-light"), tokens(src, "wol-dark")
    sc = "".join(f"  {k}: {v};\n" for k, v in scale(src))
    return (
        "/* Generated by tools/gen_theme.py from crates/core/src/theme/builtin/wol-light.json,\n"
        "   wol-dark.json and shared::theme::SCALE. Do not edit by hand.\n"
        "   Preview only: inside Atlas the engine serves the live WolOS theme under this\n"
        "   same name, so a theme change reaches the page with no code (README.md). */\n"
        ":root {\n  color-scheme: light;\n" + block(light, "  ") + sc + "}\n"
        "@media (prefers-color-scheme: dark) {\n  :root {\n    color-scheme: dark;\n"
        + block(dark, "    ") + "  }\n}\n"
    )


def render_categories(src: pathlib.Path) -> str:
    data = json.loads((src / "design/tokens/colors.json").read_text())
    cats = data["icon"]["categories"]
    rows = "".join(f"  --cat-{c}: {cats[c]['body']};\n" for c in CATEGORIES)
    return (
        "/* Generated by tools/gen_theme.py from design/tokens/colors.json (icon.categories, the\n"
        "   body colour of each). Do not edit by hand. The tile behind a pinned card. The category\n"
        "   colours do not change with the light and dark themes. Preview only: inside Atlas the\n"
        "   engine serves this file next to theme.css. */\n"
        ":root {\n" + rows + "}\n"
    )


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    src = pathlib.Path(sys.argv[1])
    out = ((OUT_THEME, render_theme(src)), (OUT_CATS, render_categories(src)))
    if "--check" in sys.argv[2:]:
        stale = [p.name for p, css in out if not p.exists() or p.read_text() != css]
        if stale:
            print(f"{', '.join(stale)} stale: run tools/gen_theme.py", file=sys.stderr)
            return 1
        print("theme.css and categories.css match the built-in themes and the design palette")
        return 0
    for p, css in out:
        p.write_text(css)
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
